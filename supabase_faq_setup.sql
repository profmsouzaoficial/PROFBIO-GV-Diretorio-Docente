CREATE TABLE IF NOT EXISTS public.perguntas_frequentes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pergunta TEXT NOT NULL,
    resposta JSONB NOT NULL,
    frequencia INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_perguntas_frequentes_frequencia 
ON public.perguntas_frequentes(frequencia DESC);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.perguntas_frequentes ENABLE ROW LEVEL SECURITY;

-- 1. Permitir leitura pública / anônima
DROP POLICY IF EXISTS "Leitura publica de perguntas frequentes" ON public.perguntas_frequentes;
CREATE POLICY "Leitura publica de perguntas frequentes" 
ON public.perguntas_frequentes FOR SELECT 
USING (true);

-- 2. Permitir inserção de novas perguntas aprendidas
DROP POLICY IF EXISTS "Insercao publica de novas perguntas frequentes" ON public.perguntas_frequentes;
CREATE POLICY "Insercao publica de novas perguntas frequentes" 
ON public.perguntas_frequentes FOR INSERT 
WITH CHECK (true);

-- 3. Permitir atualização do contador de frequência
DROP POLICY IF EXISTS "Atualizacao de frequencia de perguntas frequentes" ON public.perguntas_frequentes;
CREATE POLICY "Atualizacao de frequencia de perguntas frequentes" 
ON public.perguntas_frequentes FOR UPDATE 
USING (true)
WITH CHECK (true);
